package com.example.model

/**
 * Configuration model representing both Minecraft's server.properties
 * and server boot flags such as auto-EULA agreement and cracked/offline mode.
 */
data class ServerConfig(
    val serverPort: Int = 25565,
    val onlineMode: Boolean = false, // false = Cracked / Offline Mode (Recommended for Beta 1.7)
    val autoEula: Boolean = true,    // auto-writes eula=true into eula.txt
    val levelName: String = "world",
    val levelSeed: String = "",
    val maxPlayers: Int = 20,
    val pvp: Boolean = true,
    val spawnMonsters: Boolean = true,
    val spawnAnimals: Boolean = true,
    val viewDistance: Int = 10,
    val allowNether: Boolean = true,
    val allowFlight: Boolean = false,
    val whiteList: Boolean = false,
    val motd: String = "Minecraft Beta 1.7.3 Server on Android",
    val memoryMb: Int = 512,
    val javaCustomPath: String = "",
    val autoLanBroadcast: Boolean = true
) {
    /**
     * Converts to canonical Minecraft server.properties format
     */
    fun toPropertiesFileContent(): String {
        val sb = StringBuilder()
        sb.append("#Minecraft server properties\n")
        sb.append("#Auto-generated by MC Beta Host\n")
        sb.append("server-port=").append(serverPort).append("\n")
        sb.append("online-mode=").append(onlineMode).append("\n")
        sb.append("level-name=").append(levelName.ifBlank { "world" }).append("\n")
        sb.append("level-seed=").append(levelSeed).append("\n")
        sb.append("max-players=").append(maxPlayers).append("\n")
        sb.append("pvp=").append(pvp).append("\n")
        sb.append("spawn-monsters=").append(spawnMonsters).append("\n")
        sb.append("spawn-animals=").append(spawnAnimals).append("\n")
        sb.append("view-distance=").append(viewDistance).append("\n")
        sb.append("allow-nether=").append(allowNether).append("\n")
        sb.append("allow-flight=").append(allowFlight).append("\n")
        sb.append("white-list=").append(whiteList).append("\n")
        sb.append("motd=").append(motd.replace("\n", " ")).append("\n")
        return sb.toString()
    }

    companion object {
        fun fromPropertiesMap(map: Map<String, String>): ServerConfig {
            return ServerConfig(
                serverPort = map["server-port"]?.toIntOrNull() ?: 25565,
                onlineMode = map["online-mode"]?.toBooleanStrictOrNull() ?: false,
                levelName = map["level-name"] ?: "world",
                levelSeed = map["level-seed"] ?: "",
                maxPlayers = map["max-players"]?.toIntOrNull() ?: 20,
                pvp = map["pvp"]?.toBooleanStrictOrNull() ?: true,
                spawnMonsters = map["spawn-monsters"]?.toBooleanStrictOrNull() ?: true,
                spawnAnimals = map["spawn-animals"]?.toBooleanStrictOrNull() ?: true,
                viewDistance = map["view-distance"]?.toIntOrNull() ?: 10,
                allowNether = map["allow-nether"]?.toBooleanStrictOrNull() ?: true,
                allowFlight = map["allow-flight"]?.toBooleanStrictOrNull() ?: false,
                whiteList = map["white-list"]?.toBooleanStrictOrNull() ?: false,
                motd = map["motd"] ?: "Minecraft Beta 1.7.3 Server on Android"
            )
        }
    }
}
